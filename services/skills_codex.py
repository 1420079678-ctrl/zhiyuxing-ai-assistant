def list_skills() -> list[MentalSkill]:
    """Return all available mental codex skills."""
    return list(SKILLS_CATALOG)


def get_skill(skill_id: str | None) -> MentalSkill | None:
    """Find a mental skill by id."""
    if not skill_id:
        return None
    for skill in SKILLS_CATALOG:
        if skill.id == skill_id:
            return skill
    return None


def format_skill_prompt(skill_id: str | None) -> str:
    """Return the system prompt addon for a given skill id."""
    skill = get_skill(skill_id)
    if not skill:
        return ""
    return "\n" + skill.system_prompt_addon


